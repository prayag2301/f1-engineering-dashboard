# ── Scale presets per concept ──────────────────────────────────────────────────
# Scale vectors [sx, sy, sz] applied to component bounding box.
# Values near 1.0 = slight change; 0.7 = 30% reduction in that axis.

_SIDEPOD_SCALES = {
    "downwash":     [0.85, 0.82, 1.00],   # narrower + shorter sidepods
    "undercut":     [0.80, 0.75, 1.00],   # aggressively undercut
    "slim":         [0.78, 0.88, 0.95],   # narrow and slightly shorter
    "conventional": [1.00, 1.00, 1.00],   # base shape
}

_SIDEPOD_INLET_SCALES = {
    "downwash":     [0.80, 0.85, 1.0],
    "undercut":     [0.85, 0.70, 1.0],
    "slim":         [0.75, 0.80, 1.0],
    "conventional": [1.00, 1.00, 1.0],
}

_NOSE_SCALES = {
    "narrow":   [0.80, 0.90, 1.00],
    "wide":     [1.10, 1.00, 1.00],
    "anteater": [0.60, 0.75, 1.00],
}

_RW_SCALES = {
    "high_downforce": [1.00, 1.15, 1.10],   # taller, more chord
    "low_drag":       [0.95, 0.88, 0.90],   # lower, less chord
    "standard":       [1.00, 1.00, 1.00],
}

_RW_FLAP_SCALES = {
    "high_downforce": [1.00, 1.20, 1.10],
    "low_drag":       [0.95, 0.80, 0.90],
    "standard":       [1.00, 1.00, 1.00],
}


# ── Builder ────────────────────────────────────────────────────────────────────

def build_deform_params(team_id: str) -> dict[str, dict]:
    """
    Return a deform_params dict for generate_car_glb().

    Keys are component node names from model_generator.py.
    Values are dicts with optional "scale" and "translate" keys.
    """
    profile = TEAM_PROFILES.get(team_id)
    if not profile:
        return {}   # no deformation → base model

    params: dict[str, dict] = {}

    # Sidepods (both sides)
    sp_scale = _SIDEPOD_SCALES[profile.sidepod_concept]
    in_scale = _SIDEPOD_INLET_SCALES[profile.sidepod_concept]
    for side in ("l", "r"):
        params[f"sidepod_{side}"]       = {"scale": list(sp_scale)}
        params[f"sidepod_inlet_{side}"] = {"scale": list(in_scale)}

    # Nose cone
    nose_scale = _NOSE_SCALES[profile.nose_style]
    params["nose_cone"] = {"scale": list(nose_scale)}

    # Rear wing
    rw_scale  = _RW_SCALES[profile.rear_wing]
    flp_scale = _RW_FLAP_SCALES[profile.rear_wing]
    params["rw_main"] = {"scale": list(rw_scale)}
    params["rw_flap"] = {"scale": list(flp_scale)}
    for side in ("l", "r"):
        params[f"rw_endplate_{side}"] = {"scale": list(rw_scale)}

    return params


def deform_description(team_id: str) -> str:
    """Human-readable summary of the team's design concept."""
    p = TEAM_PROFILES.get(team_id)
    if not p:
        return "Standard base configuration"
    return (
        f"Sidepod concept: {p.sidepod_concept} | "
        f"Nose: {p.nose_style} | "
        f"Rear wing: {p.rear_wing}"
    )
