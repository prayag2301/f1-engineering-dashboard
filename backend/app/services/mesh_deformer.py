"""
Mesh deformer — Phase 2, Week 7.

Takes a base car (generated by model_generator.py) and applies team-specific
geometric deformations so each constructor has a visually distinct profile.

Deformation approach: per-component scale + translate overrides.
These are fed into generate_car_glb(deform_params=...) rather than post-
processing a finished mesh, which avoids mesh corruption and keeps the
pipeline simple.

Each team profile describes:
  - sidepod_concept: "downwash" | "undercut" | "slim" | "conventional"
  - nose_style: "narrow" | "wide" | "anteater"
  - rear_wing: "high_downforce" | "low_drag" | "standard"

The deform_params dict maps component node names → {"scale": [sx,sy,sz], "translate": [dx,dy,dz]}
"""

